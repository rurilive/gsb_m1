from segtre.array import SegArray


def main():
    print("=== 朴素逐元素区间求和 ===")
    a = SegArray([1, 2, 3, 4, 5, 6, 7, 8])
    print("  数据 -> %s" % (a.to_list(),))
    print("  区间 [0, 8) 和 -> %d" % a.range_sum(0, 8))
    print("  区间 [2, 5) 和 -> %d" % a.range_sum(2, 5))
    print("  本次看过元素数 -> %d" % a.last_cost())
    a.set_value(3, 40)
    print("  把下标 3 改成 40 后区间 [2, 5) 和 -> %d" % a.range_sum(2, 5))
    a.add_value(0, 100)
    print("  把下标 0 加上 100 后区间 [0, 4) 和 -> %d" % a.range_sum(0, 4))
    print("  区间 [4, 4) 空区间和 -> %d" % a.range_sum(4, 4))

    # TODO(线段树与懒惰传播): 在 segtre 里补出线段树建树（区间求和、区间最值查询
    # 都是对数级）、点更新（单点赋值与单点累加）、区间加与区间赋值的懒惰传播（延迟
    # 下推保证后续查询正确，并与朴素逐元素对拍一致）、可配置的合并函数（求和、最小、
    # 最大以及外部传入的可结合函数）、以及二分下降到某个前缀和达到目标时返回位置的
    # 定位之后，在这里加一段演示：先用一撮数据建好线段树，打印一个区间的和与最值，
    # 再演示区间加与区间赋值之后同一个区间的和与最值都跟着变、且与朴素逐元素算出来
    # 的完全一致；然后用可配置合并函数换一种聚合打印结果；最后对一个数据全为正的树
    # 跑一次前缀定位，打印达到目标前缀和的位置。


if __name__ == "__main__":
    main()
