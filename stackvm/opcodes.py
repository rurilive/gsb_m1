"""opcode 编码表：名称 -> (操作码, 操作数布局)。

操作数布局："" 无操作数；"u16" 后跟 2 字节无符号小端整数。
所有指令定长编码，decode 与 disasm 全部由这张表驱动，新增指令
只要在表里占一个空闲操作码即可被汇编、反汇编和执行识别。
"""

OPS = {
    "PUSH":        (0x10, "u16"),  # 压入立即数（0~65535）
    "POP":         (0x11, ""),
    "DUP":         (0x12, ""),
    "ADD":         (0x13, ""),
    "SUB":         (0x14, ""),
    "MUL":         (0x15, ""),
    "EQ":          (0x16, ""),     # 弹出 b、a，压入 a == b
    "LT":          (0x17, ""),     # 压入 a < b
    "GT":          (0x18, ""),     # 压入 a > b
    "JMP":         (0x20, "u16"),  # 无条件跳转到字节偏移
    "JZ":          (0x21, "u16"),  # 弹栈，假值（False/0）时跳转
    "LOAD_G":      (0x22, "u16"),  # 全局段[槽位] 压栈
    "STORE_G":     (0x23, "u16"),  # 弹栈，存入全局段[槽位]
    "LOAD_LOCAL":  (0x24, "u16"),  # 局部段[编号] 压栈
    "STORE_LOCAL": (0x25, "u16"),  # 弹栈，存入局部段[编号]
    "PRINT":       (0x26, ""),     # 弹栈，str() 追加到输出
    "HALT":        (0x27, ""),     # 停机
}

BY_CODE = {code: (name, layout) for name, (code, layout) in OPS.items()}
