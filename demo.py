"""prefixsum 现状演示。

第一段：搭一小串数，用朴素逐项累加看一次点更新与几次区间求和的结果，顺带
看看一次区间查询看过多少元素；
第二段：预留的树状数组改造演示位子（见文末注释）。
"""

from prefixsum.sum import ScanSum


def main():
    print("=== 朴素逐项累加区间和 ===")
    a = ScanSum([3, 1, 4, 1, 5, 9, 2, 6])
    print("  数据 -> %s" % (a.to_list(),))
    print("  区间 [0, 8) 和 -> %d" % a.query(0, 8))
    print("  区间 [2, 6) 和 -> %d" % a.query(2, 6))
    print("  本次看过元素数 -> %d" % a.last_cost())
    a.update(3, 10)
    print("  把下标 3 加上 10 后区间 [2, 6) 和 -> %d" % a.query(2, 6))
    a.update(0, -1)
    print("  把下标 0 减去 1 后区间 [0, 4) 和 -> %d" % a.query(0, 4))
    print("  区间 [5, 5) 空区间和 -> %d" % a.query(5, 5))

    # TODO(树状数组改造): 在 prefixsum 里补出树状数组（点更新与前缀和都是
    # 对数级，区间和由两个前缀和相减得到，与逐项累加口径在任意序列上逐项一致）、
    # 差分树状数组（区间加与单点查询，与先区间加再逐点读取的暴力口径一致）、
    # 二维扩展（二维点更新与子矩阵求和，或二维区间加与单点查，与二维暴力一致）、
    # 逆序对或前缀最值（择一，与暴力口径一致）、零基下标约定与越界负数 fail
    # fast、空数组查询返回零之后，在这里加第二段演示：先对一小串数跑一轮点更新
    # 与区间求和，打印树状数组给出的区间和并说明它与逐项累加算出来的完全一致；
    # 再演示一次区间加与单点查询，说明结果与暴力口径一致。


if __name__ == "__main__":
    main()
